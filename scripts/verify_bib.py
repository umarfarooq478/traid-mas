"""Verify every entry of paper/refs.bib against Crossref (DOI), the arXiv API (arXiv id) or DBLP (title).
Writes research/reference_check.md. Usage: python scripts/verify_bib.py"""
import json, re, sys, time, urllib.parse, urllib.request, xml.etree.ElementTree as ET
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
UA = {"User-Agent": "refcheck/0.2 (academic reference verification)"}
def get(u, tries=4):
    for i in range(tries):
        try:
            t = urllib.request.urlopen(urllib.request.Request(u, headers=UA), timeout=60).read().decode()
            if t.lstrip()[:1] in "{<" and "not a bot" not in t[:500]:
                return t
        except Exception:
            if i == tries - 1:
                raise
        time.sleep(4 * (i + 1))
    raise RuntimeError("no usable response")
norm = lambda s: re.sub(r"[^a-z0-9]", "", re.sub(r"\\[a-z]+|[{}]", "", s.lower()))
bib = (ROOT / "paper" / "refs.bib").read_text(encoding="utf-8")
entries = re.findall(r"@(\w+)\{([^,]+),(.*?)\n\}", bib, re.S)
field = lambda body, f: (re.search(rf"\b{f}\s*=\s*\{{(.*?)\}},?\s*\n", body, re.S) or [None, ""])[1].replace("\n", " ")
rows = []
ONLY = set(sys.argv[1:])
for typ, key, body in entries:
    if ONLY and key not in ONLY:
        continue
    title, year = field(body, "title"), field(body, "year")
    first = re.split(r"\s+and\s+", field(body, "author"))[0].split(",")[0].strip("{} ")
    doi, ax = field(body, "doi"), re.search(r"arXiv:(\d{4}\.\d{4,5})", body)
    src, found, status = "", "", "NOT FOUND"
    try:
        if doi:
            m = json.loads(get("https://api.crossref.org/works/" + urllib.parse.quote(doi)))["message"]
            ft = (m.get("title") or [""])[0]; fy = (m.get("issued", {}).get("date-parts") or [[None]])[0][0]
            fa = (m.get("author") or [{}])[0].get("family", "")
            src, found = f"Crossref doi:{doi}", f"{ft} ({fy}; {fa}; {(m.get('container-title') or [''])[0]})"
        elif ax:
            x = get(f"https://export.arxiv.org/api/query?id_list={ax.group(1)}")
            ns = {"a": "http://www.w3.org/2005/Atom"}; e = ET.fromstring(x).find("a:entry", ns)
            ft = " ".join(e.find("a:title", ns).text.split()); fy = e.find("a:published", ns).text[:4]
            fa = e.find("a:author/a:name", ns).text.split()[-1]
            src, found = f"arXiv:{ax.group(1)}", f"{ft} ({fy}; {fa})"
        else:
            items = json.loads(get("https://api.crossref.org/works?rows=5&query.bibliographic=" + urllib.parse.quote(title)))["message"]["items"]
            items = [i for i in items if norm((i.get("title") or [""])[0])[:40] == norm(title)[:40]]
            if items:
                m = items[0]; ft = m["title"][0]; fy = (m.get("issued", {}).get("date-parts") or [[None]])[0][0]
                fa = (m.get("author") or [{}])[0].get("family", "")
                src, found = f"Crossref search doi:{m.get('DOI')}", f"{ft} ({fy}; {fa}; {(m.get('container-title') or [''])[0]})"
            else:
                h = json.loads(get("https://api.semanticscholar.org/graph/v1/paper/search?limit=3&fields=title,year,venue,authors&query=" + urllib.parse.quote(title)))
                hits = [x for x in h.get("data", []) if norm(x["title"])[:40] == norm(title)[:40]]
                if hits:
                    x = hits[0]; ft, fy = x["title"], x.get("year"); fa = (x.get("authors") or [{"name": ""}])[0]["name"].split()[-1]
                    src, found = f"SemanticScholar {x.get('paperId','')[:10]}", f"{ft} ({fy}; {fa}; {x.get('venue','')})"
        if found:
            ok_t = norm(ft)[:45] == norm(title)[:45]
            ok_a = norm(fa)[:5] == norm(first.split()[-1])[:5]
            status = "verified" if ok_t and ok_a else f"CHECK (title {'ok' if ok_t else 'MISMATCH'}, first author {'ok' if ok_a else 'MISMATCH'})"
    except Exception as ex:
        status = f"ERROR {str(ex)[:60]}"
    rows.append((key, src, status, found, f"{title} ({year}; {first})"))
    print(key, "|", status, "|", found[:110]); time.sleep(8)
out = ["# Reference verification log", "", "Generated by `scripts/verify_bib.py` (Crossref for DOIs, arXiv API for arXiv ids, DBLP otherwise).", "",
       "| key | source | status | record found | bib entry |", "|---|---|---|---|---|"]
out += [f"| {k} | {s} | {st} | {f} | {b} |" for k, s, st, f, b in rows]
dest = ROOT / "research" / ("reference_check.md" if not ONLY else "reference_check_retry.md")
dest.write_text("\n".join(out) + "\n", encoding="utf-8")
